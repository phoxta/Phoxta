/**
 * The hub lists every product by its commercial name, but must not import all
 * seventeen product modules (each is a few hundred lines). This extracts the
 * handful of fields the hub needs into a tiny module.
 *
 *   node scripts/build-product-index.mjs
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = path.dirname(path.dirname(fileURLToPath(import.meta.url)))
const DIR = path.join(ROOT, 'src', 'content', 'product')
const OUT = path.join(ROOT, 'src', 'content', 'productIndex.ts')

const field = (src, key) => {
  const m = src.match(new RegExp(`\\n  ${key}:\\s*(?:'((?:[^'\\\\]|\\\\.)*)'|"((?:[^"\\\\]|\\\\.)*)")`))
  if (!m) return null
  return (m[1] ?? m[2]).replace(/\\'/g, "'").replace(/\\"/g, '"').replace(/\\\\/g, '\\')
}

const entries = []
for (const f of readdirSync(DIR).filter((f) => f.endsWith('.ts')).sort()) {
  const slug = f.replace(/\.ts$/, '')
  const src = readFileSync(path.join(DIR, f), 'utf8')
  const name = field(src, 'name')
  const tagline = field(src, 'tagline')
  const category = field(src, 'category')
  if (!name) { console.warn(`[product-index] ${slug}: no name found, skipping`); continue }
  entries.push({ slug, name, tagline, category })
}

const esc = (s) => (s == null ? 'undefined' : `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`)

const body = `/**
 * Generated by scripts/build-product-index.mjs — do not edit by hand.
 * The commercial name and one-line pitch for each product that has a written
 * positioning module, so the hub can list them without importing all of them.
 */
import type { Slug } from './types'

export interface ProductBrief {
  name: string
  tagline?: string
  category?: string
}

export const PRODUCT_INDEX: Partial<Record<Slug, ProductBrief>> = {
${entries.map((e) => `  '${e.slug}': { name: ${esc(e.name)}, tagline: ${esc(e.tagline)}, category: ${esc(e.category)} },`).join('\n')}
}

export const productBrief = (slug: Slug): ProductBrief | undefined => PRODUCT_INDEX[slug]
`

writeFileSync(OUT, body)
console.log(`[product-index] ${entries.length} products → src/content/productIndex.ts`)
for (const e of entries) console.log(`  ${e.slug.padEnd(14)} ${e.name}`)
